"""Generates docs/THIRD-PARTY-LICENSES.md from `cargo metadata`.

Usage (repository root):  python scripts/third-party.py
Lists every crate compiled into the Windows release binary (normal dependencies
only, resolved for x86_64-pc-windows-msvc), with version, licence and source.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = "x86_64-pc-windows-msvc"


def main() -> int:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            cwd=ROOT, check=True, capture_output=True, text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root_id = meta["resolve"]["root"]

    # Walk normal (non-dev, non-build) dependencies from the root.
    seen, stack = set(), [root_id]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])

    rows = sorted(
        (packages[i]["name"], packages[i]["version"], packages[i].get("license") or "see source",
         packages[i].get("repository") or "")
        for i in seen
    )
    out = [
        "# Third-party licenses / Licences tierces",
        "",
        "Generated by `scripts/third-party.py` from `Cargo.lock` — do not edit by hand.",
        "Généré par `scripts/third-party.py` depuis `Cargo.lock` — ne pas modifier à la main.",
        "",
        f"Crates compiled into the Windows release binary / crates compilés dans le binaire Windows : **{len(rows)}**.",
        "",
        "The `unrar` crate embeds the UnRAR C++ library, distributed under the UnRAR licence: it may be",
        "used to extract archives, but not to re-create the RAR compression algorithm.",
        "Le crate `unrar` embarque la bibliothèque C++ UnRAR (licence UnRAR) : extraction autorisée,",
        "recréation de l'algorithme de compression RAR interdite.",
        "",
        "| Crate | Version | License / Licence | Source |",
        "|---|---|---|---|",
    ]
    for name, version, lic, repo in rows:
        link = f"[link]({repo})" if repo else ""
        out.append(f"| `{name}` | {version} | {lic} | {link} |")
    path = ROOT / "docs" / "THIRD-PARTY-LICENSES.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{path.relative_to(ROOT)}: {len(rows)} crates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
