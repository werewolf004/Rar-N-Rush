//! Helpers shared by the integration tests.
#![allow(dead_code, clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Folder holding the committed RAR fixtures.
pub fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
}

/// Copies fixtures (by file name) into `dir`.
pub fn copy_fixtures(dir: &Path, names: &[&str]) {
    for name in names {
        fs::copy(fixtures().join(name), dir.join(name)).unwrap();
    }
}

/// The 60 000-byte payload stored in `multi.part*.rar` (same xorshift32 as the script).
pub fn payload() -> Vec<u8> {
    let mut x: u32 = 2_463_534_242;
    (0..60_000)
        .map(|_| {
            x ^= x << 13;
            x ^= x >> 17;
            x ^= x << 5;
            (x & 0xFF) as u8
        })
        .collect()
}

/// Minimal PAR2 packet (hashes are not checked by Rar N Rush).
pub fn par2_packet(kind: &[u8; 16], body: &[u8]) -> Vec<u8> {
    let mut p = b"PAR2\0PKT".to_vec();
    p.extend_from_slice(&(64 + body.len() as u64).to_le_bytes());
    p.extend_from_slice(&[0u8; 32]);
    p.extend_from_slice(kind);
    p.extend_from_slice(body);
    p
}

/// Writes a PAR2 file whose `FileDesc` packets list `targets`.
pub fn write_par2(path: &Path, targets: &[&str]) {
    let mut data = Vec::new();
    for t in targets {
        let mut body = vec![0u8; 56];
        body.extend_from_slice(t.as_bytes());
        while !body.len().is_multiple_of(4) {
            body.push(0);
        }
        data.extend(par2_packet(b"PAR 2.0\0FileDesc", &body));
    }
    fs::write(path, data).unwrap();
}

/// Writes an SFV file with the real CRC32 of each listed file in `dir`.
pub fn write_sfv(dir: &Path, sfv: &str, files: &[&str]) {
    let mut text = String::from("; generated by tests\n");
    for f in files {
        let crc = crc32fast::hash(&fs::read(dir.join(f)).unwrap());
        writeln!(text, "{f} {crc:08x}").unwrap();
    }
    fs::write(dir.join(sfv), text).unwrap();
}

/// Writes a fake `par2` batch script that prints `stdout` lines and exits with `code`.
pub fn fake_par2(dir: &Path, name: &str, stdout: &[&str], stderr: Option<&str>, code: i32) -> PathBuf {
    let mut script = String::from("@echo off\r\n");
    for line in stdout {
        write!(script, "echo {line}\r\n").unwrap();
    }
    if let Some(e) = stderr {
        write!(script, "echo {e} 1>&2\r\n").unwrap();
    }
    write!(script, "exit /b {code}\r\n").unwrap();
    let path = dir.join(name);
    fs::write(&path, script).unwrap();
    path
}
